// Port of supabase/functions/generate-seed-images. Generates a subject, category or course image
// with Google's Gemini image model (key from ai_settings 'ai_api_config', provider 'google') and
// stores it in the question-images bucket on this server. Auth: Bearer user token.
// Note: the original returned a permanent public URL. This server has no public bucket route, so
// the image URL is a signed URL that lasts IMAGE_URL_TTL_SEC (10 years).
import express from "express";
import jwt from "jsonwebtoken";
import { query } from "../_shared/db.js";
import { upload, createSignedUrl } from "../_shared/storage.js";

export const router = express.Router();

// Test hook: lets tests stub the Google call so no real request is sent.
export const hooks = { fetch: (...args) => fetch(...args) };

const BUCKET = "question-images";
const IMAGE_URL_TTL_SEC = 10 * 365 * 24 * 60 * 60;

function hasValidBearer(req) {
  const h = req.get("Authorization") || "";
  if (!h.startsWith("Bearer ")) return false;
  try {
    return Boolean(jwt.verify(h.slice(7), process.env.JWT_SECRET)?.sub);
  } catch {
    return false;
  }
}

function promptFor(entityType, entityName, entityDescription) {
  if (entityType === "subject") {
    return `Create a professional, vibrant educational thumbnail image for ${entityName} subject. The image should be modern, engaging, and represent ${entityDescription}. Use bright colors, include relevant symbols or icons related to the subject, and make it suitable for an online learning platform. High quality, 16:9 aspect ratio.`;
  }
  if (entityType === "category") {
    return `Create a professional, inspiring banner image for educational category: ${entityName}. ${entityDescription}. The image should be motivational, modern, and appealing to Indian students. Include subtle educational elements. High quality, wide banner format, 16:9 aspect ratio.`;
  }
  if (entityType === "course") {
    return `Create an engaging course thumbnail for: ${entityName}. ${entityDescription}. The image should be professional, modern, and appealing to students. Include relevant educational symbols, use vibrant colors, and make it eye-catching for an online course. High quality, 16:9 aspect ratio.`;
  }
  return "";
}

router.post("/", async (req, res) => {
  try {
    if (!hasValidBearer(req)) return res.status(401).json({ error: "Unauthorized" });
    const { entityType, entityName, entityDescription } = req.body || {};
    console.log(`Generating image for ${entityType}: ${entityName}`);

    const { rows } = await query(
      "SELECT setting_value FROM public.ai_settings WHERE setting_key = 'ai_api_config' LIMIT 1",
    );
    const config = rows[0]?.setting_value;

    if (!config?.enabled || config?.provider !== "google" || !config?.google_api_key) {
      console.error("[generate-seed-images] Google API key not configured for image generation");
      return res.status(503).json({
        error: "Google AI API not configured. Image generation requires a Google API key. Please go to Admin → Settings → AI Functions API Key Settings.",
        success: false,
      });
    }

    const prompt = promptFor(entityType, entityName, entityDescription);

    const response = await hooks.fetch(
      "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-image:generateContent",
      {
        method: "POST",
        headers: { "Content-Type": "application/json", "x-goog-api-key": config.google_api_key },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { responseModalities: ["TEXT", "IMAGE"] },
        }),
        signal: AbortSignal.timeout(120_000),
      },
    );

    if (!response.ok) {
      console.error("Google AI error:", response.status);
      if (response.status === 429) {
        return res.status(429).json({ error: "Rate limit exceeded. Please try again later.", success: false });
      }
      if (response.status === 401 || response.status === 403) {
        return res.status(response.status).json({ error: "Invalid or unauthorized Google API key.", success: false });
      }
      throw new Error(`Google AI error: ${response.status}`);
    }

    const data = await response.json();
    const parts = data.candidates?.[0]?.content?.parts || [];
    const imagePart = parts.find((part) => part.inlineData?.mimeType?.startsWith("image/"));
    if (!imagePart?.inlineData?.data) {
      console.error("No image in Google response");
      throw new Error("No image generated by Google AI");
    }

    const mimeType = imagePart.inlineData.mimeType || "image/png";
    const extension = mimeType.split("/")[1] || "png";
    const imageBuffer = Buffer.from(imagePart.inlineData.data, "base64");

    const fileName = `${entityType}/${String(entityName).toLowerCase().replace(/\s+/g, "-")}-${Date.now()}.${extension}`;
    await upload(BUCKET, fileName, imageBuffer);
    const imageUrl = createSignedUrl(BUCKET, fileName, IMAGE_URL_TTL_SEC);

    res.json({ success: true, imageUrl, entityName, entityType });
  } catch (error) {
    console.error("Error generating image:", error?.message);
    res.status(500).json({
      error: error instanceof Error ? error.message : "Unknown error",
      success: false,
    });
  }
});
